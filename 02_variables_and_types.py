"""
Topic: Variables and Data Types
A variable is a name that stores a value in memory so you can reuse it.
Python has several basic data types: str (text), int (whole numbers),
float (decimal numbers), and bool (True/False).
"""

name = "Zohaib"        # str: text, written in quotes
age = 21                # int: whole number
height = 1.75           # float: decimal number
is_student = True       # bool: True or False

print(name)
print(age)
print(height)
print(is_student)

print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
